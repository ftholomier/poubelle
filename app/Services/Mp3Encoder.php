    /**
     * Encode des échantillons PCM 16 bits mono (petit-boutiste, comme ceux de Gemini) en MP3.
     * Les dernières trames vident le banc de filtres : rien de la fin de la voix n'est perdu.
     */
    public static function encode(string $pcm, int $rate, int $kbps = 48): string
    {
        if (!isset(self::RATES[$rate], self::BITRATES[$kbps])) {
            throw new \InvalidArgumentException("MP3 : $rate Hz ou $kbps kbit/s non pris en charge.");
        }
        self::init();
        $sfb = self::SFB[$rate];
        $head = "\xFF\xF3"; // synchronisation, MPEG-2, Layer III, sans CRC
        $hb = self::BITRATES[$kbps] << 4 | self::RATES[$rate] << 2;
        // Octets par trame (une granule de 576 échantillons) : une trame sur n prend un octet de plus si besoin.
        $avg = 72000 * $kbps / $rate;
        $whole = (int) floor($avg);
        $frac = $avg - $whole;
        $lag = -$frac;
        [$w0, $w1, $w2, $w3, $w4, $w5, $w6, $w7] = self::$win;
        $dct = self::$dct;
        $mdct = self::$mdct;
        $cs = self::$cs;
        $ca = self::$ca;

        $granules = intdiv(intdiv(strlen($pcm), 2) + 1152 + 575, 576);
        $buf = array_fill(0, 480, 0.0);
        $prev = array_fill(0, 18, array_fill(0, 32, 0.0));
        $out = '';
        for ($g = 0; $g < $granules; $g++) {
            // 576 nouveaux échantillons dans [-1, 1[ (des zéros après la fin), derrière les 480 précédents.
            $chunk = substr($pcm, $g * 1152, 1152);
            if (strlen($chunk) < 1152) {
                $chunk = str_pad($chunk, 1152, "\0");
            }
            $buf = array_slice($buf, -480);
            foreach (unpack('v576', $chunk) as $v) {
                $buf[] = ($v > 32767 ? $v - 65536 : $v) * 3.0517578125E-5;
            }

            // Banc de filtres polyphase : 18 instants × 32 sous-bandes.
            $sb = [];
            for ($t = 0; $t < 18; $t++) {
                $q = 511 + ($t << 5);
                $y = [];
                for ($k = 0; $k < 64; $k++) {
                    $p = $q - $k;
                    $y[$k] = $w0[$k] * $buf[$p] + $w1[$k] * $buf[$p - 64] + $w2[$k] * $buf[$p - 128] + $w3[$k] * $buf[$p - 192]
                        + $w4[$k] * $buf[$p - 256] + $w5[$k] * $buf[$p - 320] + $w6[$k] * $buf[$p - 384] + $w7[$k] * $buf[$p - 448];
                }
                $a = [$y[16]];
                for ($m = 1; $m < 17; $m++) {
                    $a[$m] = $y[16 + $m] + $y[16 - $m];
                }
                for ($m = 17; $m < 32; $m++) {
                    $a[$m] = $y[16 + $m] - $y[80 - $m];
                }
                $s = [];
                foreach ($dct as $i => $c) {
                    $acc = 0.0;
                    foreach ($a as $m => $v) {
                        $acc += $c[$m] * $v;
                    }
                    // Sous-bandes impaires inversées en fréquence : un instant sur deux change de signe.
                    $s[$i] = ($t & $i & 1) ? -$acc : $acc;
                }
                $sb[$t] = $s;
            }

            // MDCT de chaque sous-bande (18 instants précédents + 18 actuels), puis réduction du repliement.
            $xr = [];
            for ($b = 0; $b < 32; $b++) {
                $in = [];
                for ($t = 0; $t < 18; $t++) {
                    $in[$t] = $prev[$t][$b];
                }
                for ($t = 0; $t < 18; $t++) {
                    $in[18 + $t] = $sb[$t][$b];
                }
                foreach ($mdct as $c) {
                    $acc = 0.0;
                    foreach ($in as $k => $v) {
                        $acc += $c[$k] * $v;
                    }
                    $xr[] = $acc;
                }
                if ($b > 0) {
                    $o = 18 * $b;
                    for ($i = 0; $i < 8; $i++) {
                        $lo = $o - 1 - $i;
                        $hi = $o + $i;
                        $bu = $xr[$lo];
                        $bd = $xr[$hi];
                        $xr[$lo] = $bu * $cs[$i] + $bd * $ca[$i];
                        $xr[$hi] = $bd * $cs[$i] - $bu * $ca[$i];
                    }
                }
            }
            $prev = $sb;

            $pad = 0;
            if ($frac > 0) {
                $pad = $lag <= $frac - 1.0 ? 1 : 0;
                $lag += $pad - $frac;
            }
            $bytes = $whole + $pad;
            $main = self::granule($xr, $sfb, min(4095, $bytes * 8 - 104), $side);
            $out .= $head . chr($hb | $pad << 1) . "\xC4" // mono, original
                . hex2bin(strtr(str_pad($side . $main, ($bytes - 4) * 8, '0'), self::$hex));
        }
        return $out;
    }

    /**
     * Quantifie et code une granule dans $maxBits au plus : le pas le plus fin qui tient (recherche
     * par dichotomie puis pas à pas, comme shine). Renvoie les données principales (« 0 »/« 1 ») et
     * les informations annexes de la granule dans $side.
     */
    private static function granule(array $xr, array $sfb, int $maxBits, ?string &$side): string
    {
        $a75 = [];
        $neg = [];
        $mx = 0.0;
        foreach ($xr as $i => $v) {
            if ($v < 0) {
                $v = -$v;
                $neg[$i] = true;
            }
            $a = $v ** 0.75;
            $a75[$i] = $a;
            if ($a > $mx) {
                $mx = $a;
            }
        }
        $q = null;
        if ($mx > 1e-9) {
            $next = -120;
            $count = 120;
            do {
                $half = intdiv($count, 2);
                if (self::count($a75, $mx, $next + $half, $sfb) < $maxBits) {
                    $count = $half;
                } else {
                    $next += $half;
                    $count -= $half;
                }
            } while ($count > 1);
            for ($ss = $next + 1; $ss <= 45; $ss++) {
                if (self::count($a75, $mx, $ss, $sfb, $q) <= $maxBits) {
                    break;
                }
                $q = null;
            }
        }
        if ($q === null) {
            // Silence (ou rien ne tient) : granule vide.
            $side = sprintf('%09b%012b%09b%08b%028b', 0, 0, 0, 210, 0) . str_repeat('0', 6);
            return '';
        }
        [$ix, $bvr, $count1, $c1, $t0, $t1, $t2, $r0, $r1, $gg] = $q;

        $code = self::$code;
        $main = '';
        $reg1 = $sfb[$r0 + 1];
        $reg2 = $sfb[$r0 + $r1 + 2];
        for ($i = 0; $i < $bvr; $i += 2) {
            $t = $i < $reg1 ? $t0 : ($i < $reg2 ? $t1 : $t2);
            if ($t === 0) {
                continue;
            }
            $x = $ix[$i];
            $y = $ix[$i + 1];
            if ($t < 16) {
                $main .= $code[$t][$x << 4 | $y] . ($x ? (isset($neg[$i]) ? '1' : '0') : '') . ($y ? (isset($neg[$i + 1]) ? '1' : '0') : '');
                continue;
            }
            $lin = self::LINBITS[$t];
            $main .= $code[$t < 24 ? 16 : 24][($x > 14 ? 15 : $x) << 4 | ($y > 14 ? 15 : $y)]
                . ($x > 14 ? str_pad(decbin($x - 15), $lin, '0', STR_PAD_LEFT) : '') . ($x ? (isset($neg[$i]) ? '1' : '0') : '')
                . ($y > 14 ? str_pad(decbin($y - 15), $lin, '0', STR_PAD_LEFT) : '') . ($y ? (isset($neg[$i + 1]) ? '1' : '0') : '');
        }
        $quad = $code[32 + $c1];
        for ($i = $bvr, $e = $bvr + 4 * $count1; $i < $e; $i += 4) {
            $main .= $quad[$ix[$i] << 3 | $ix[$i + 1] << 2 | $ix[$i + 2] << 1 | $ix[$i + 3]]
                . ($ix[$i] ? (isset($neg[$i]) ? '1' : '0') : '') . ($ix[$i + 1] ? (isset($neg[$i + 1]) ? '1' : '0') : '')
                . ($ix[$i + 2] ? (isset($neg[$i + 2]) ? '1' : '0') : '') . ($ix[$i + 3] ? (isset($neg[$i + 3]) ? '1' : '0') : '');
        }
        if (strlen($main) > $maxBits) {
            throw new \LogicException('MP3 : granule plus longue que prévu.');
        }
        // main_data_begin, bits privés, puis la granule : longueur, grandes valeurs, gain global,
        // scalefac_compress (aucun facteur d'échelle), blocs longs, tables, régions, échelle, quadruplets.
        $side = sprintf('%08b%01b%012b%09b%08b%09b%01b%05b%05b%05b%04b%03b%01b%01b',
            0, 0, strlen($main), $bvr >> 1, $gg, 0, 0, $t0, $t1, $t2, $r0, $r1, 0, $c1);
        return $main;
    }

    /**
     * Nombre de bits de la granule quantifiée avec le pas $ss (PHP_INT_MAX : hors des tables).
     * $q reçoit ce qu'il faut pour l'écrire : [valeurs, fin des grandes valeurs, quadruplets,
     * table des quadruplets, tables des 3 régions, region0_count, region1_count, gain global].
     */
    private static function count(array $a75, float $mx, int $ss, array $sfb, ?array &$q = null): int
    {
        $f = 2 ** (-0.1875 * $ss); // (2^(-ss/4))^(3/4)
        if ((int) ($mx * $f + 0.4054) > self::IXMAX) {
            return PHP_INT_MAX;
        }
        $ix = [];
        foreach ($a75 as $i => $a) {
            $ix[$i] = (int) ($a * $f + 0.4054);
        }
        // Zéros à la fin, puis quadruplets de 0 et de 1, puis les grandes valeurs.
        $i = 576;
        while ($i > 1 && $ix[$i - 1] === 0 && $ix[$i - 2] === 0) {
            $i -= 2;
        }
        $count1 = 0;
        while ($i > 3 && $ix[$i - 1] <= 1 && $ix[$i - 2] <= 1 && $ix[$i - 3] <= 1 && $ix[$i - 4] <= 1) {
            $count1++;
            $i -= 4;
        }
        $bvr = $i;
        $la = self::$len[32];
        $lb = self::$len[33];
        $sa = $sb = 0;
        for ($j = $bvr, $e = $bvr + 4 * $count1; $j < $e; $j += 4) {
            $p = $ix[$j] << 3 | $ix[$j + 1] << 2 | $ix[$j + 2] << 1 | $ix[$j + 3];
            $sa += $la[$p];
            $sb += $lb[$p];
        }
        $c1 = $sb < $sa ? 1 : 0;
        $bits = $c1 ? $sb : $sa;
        $r0 = $r1 = 0;
        $a1 = $a2 = $bvr;
        if ($bvr > 0) {
            $n = 0;
            while ($sfb[$n] < $bvr) {
                $n++;
            }
            [$r0, $r1] = self::SUBDV[$n];
            while ($r0 > 0 && $sfb[$r0 + 1] > $bvr) {
                $r0--;
            }
            while ($r1 > 0 && $sfb[$r0 + $r1 + 2] > $bvr) {
                $r1--;
            }
            $a1 = min($sfb[$r0 + 1], $bvr);
            $a2 = min($sfb[$r0 + $r1 + 2], $bvr);
        }
        $t0 = self::choose($ix, 0, $a1, $bits);
        $t1 = self::choose($ix, $a1, $a2, $bits);
        $t2 = self::choose($ix, $a2, $bvr, $bits);
        $q = [$ix, $bvr, $count1, $c1, $t0, $t1, $t2, $r0, $r1, $ss + 210];
        return $bits;
    }

    /** Table de Huffman la moins coûteuse pour les valeurs $ix[$b..$e[ ; ajoute son coût à $bits. */
    private static function choose(array $ix, int $b, int $e, int &$bits): int
    {
        $max = 0;
        for ($i = $b; $i < $e; $i++) {
            if ($ix[$i] > $max) {
                $max = $ix[$i];
            }
        }
        if ($max === 0) {
            return 0;
        }
        if ($max < 15) {
            // Plus petite table assez large, puis ses voisines de même largeur.
            $group = match (true) {
                $max === 1 => [1],
                $max === 2 => [2, 3],
                $max === 3 => [5, 6],
                $max <= 5 => [7, 8, 9],
                $max <= 7 => [10, 11, 12],
                default => [13, 15],
            };
            $best = 0;
            $cost = PHP_INT_MAX;
            foreach ($group as $t) {
                $l = self::$len[$t];
                $s = 0;
                for ($i = $b; $i < $e; $i += 2) {
                    $s += $l[$ix[$i] << 4 | $ix[$i + 1]];
                }
                if ($s < $cost) {
                    $cost = $s;
                    $best = $t;
                }
            }
            $bits += $cost;
            return $best;
        }
        // Valeurs de 15 et plus : codes des tables 16 ou 24, et des bits en plus (linbits).
        $l16 = self::$len[16];
        $l24 = self::$len[24];
        $s16 = $s24 = $esc = 0;
        for ($i = $b; $i < $e; $i += 2) {
            $x = $ix[$i];
            $y = $ix[$i + 1];
            if ($x > 14) {
                $x = 15;
                $esc++;
            }
            if ($y > 14) {
                $y = 15;
                $esc++;
            }
            $s16 += $l16[$x << 4 | $y];
            $s24 += $l24[$x << 4 | $y];
        }
        $t16 = 16;
        while ((1 << self::LINBITS[$t16]) - 1 < $max - 15) {
            $t16++;
        }
        $t24 = 24;
        while ((1 << self::LINBITS[$t24]) - 1 < $max - 15) {
            $t24++;
        }
        $s16 += $esc * self::LINBITS[$t16];
        $s24 += $esc * self::LINBITS[$t24];
        $bits += min($s16, $s24);
        return $s24 < $s16 ? $t24 : $t16;
    }

    private static function init(): void
    {
        if (self::$ready) {
            return;
        }
        for ($j = 0; $j < 8; $j++) {
            self::$win[$j] = array_slice(self::WIN, 64 * $j, 64);
        }
        // Matrice du banc de filtres cos((2i + 1)(k − 16)π/64), 64 colonnes repliées en 32.
        for ($i = 0; $i < 32; $i++) {
            for ($m = 0; $m < 32; $m++) {
                self::$dct[$i][$m] = cos((2 * $i + 1) * $m * M_PI / 64);
            }
        }
        // MDCT divisée par 9 (n/4) : le décodeur, qui ne la normalise pas, rend le niveau d'origine.
        for ($m = 0; $m < 18; $m++) {
            for ($k = 0; $k < 36; $k++) {
                self::$mdct[$m][$k] = sin(M_PI / 36 * ($k + 0.5)) * cos(M_PI / 72 * (2 * $k + 19) * (2 * $m + 1)) / 9;
            }
        }
        foreach ([-0.6, -0.535, -0.33, -0.185, -0.095, -0.041, -0.0142, -0.0037] as $i => $c) {
            $r = sqrt(1 + $c * $c);
            self::$cs[$i] = 1 / $r;
            self::$ca[$i] = $c / $r;
        }
        foreach (self::HUFF as $t => [$codes, $lens]) {
            foreach ($codes as $idx => $c) {
                $s = str_pad(decbin($c), $lens[$idx], '0', STR_PAD_LEFT);
                if ($t >= 32) {
                    // Quadruplets : 8v + 4w + 2x + y, un bit de signe par valeur non nulle.
                    self::$code[$t][$idx] = $s;
                    self::$len[$t][$idx] = $lens[$idx] + substr_count(decbin($idx), '1');
                    continue;
                }
                $x = intdiv($idx, self::XLEN[$t]);
                $y = $idx % self::XLEN[$t];
                self::$code[$t][$x << 4 | $y] = $s;
                self::$len[$t][$x << 4 | $y] = $lens[$idx] + ($x ? 1 : 0) + ($y ? 1 : 0);
            }
        }
        for ($i = 0; $i < 16; $i++) {
            self::$hex[sprintf('%04b', $i)] = dechex($i);
        }
        self::$ready = true;
    }
}
